-- เพิ่มรูปแบบ 'feature' — คลิปยาวพิเศษ (~45 นาที) ที่เขียนโดยวางโครงก่อนแล้วเขียนทีละท่อน
--
-- แยกจาก 'long' เพราะวิธีเขียนต่างกันคนละแบบ ไม่ใช่แค่ยาวกว่า:
-- 'long' ขอสคริปต์รวดเดียว · 'feature' วางหัวข้อย่อยก่อน แล้วให้โมเดลเขียนทีละท่อนต่อกัน
-- (ขอ 40,000+ ตัวอักษรในครั้งเดียว โมเดลจะเริ่มวนซ้ำและหลุดประเด็นกลางทาง)
--
-- ⚠️ alter type ... add value ต้องอยู่ใน migration ของตัวเองและห้ามมี statement อื่น
-- ที่ "ใช้" ค่าใหม่ตามมาใน transaction เดียวกัน — Postgres ยังไม่เห็นค่าใหม่จนกว่าจะ commit

alter type video_format add value if not exists 'feature';

comment on type video_format is
  'long = ยาว 16:9 เขียนรวดเดียว · short = สั้น 9:16 · feature = ยาวพิเศษ 16:9 เขียนทีละท่อนตามโครง';
