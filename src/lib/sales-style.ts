/**
 * ส่วนของ prompt สำหรับสไตล์นี้
 *
 * โทน informative ไม่ต้องมีอะไรเพิ่ม — เป็นพฤติกรรมเดิมของระบบอยู่แล้ว
 * คืนสตริงว่างไปแล้วให้ผู้เรียกกรองทิ้ง ดีกว่าใส่ย่อหน้าว่า "ไม่ต้องทำอะไรพิเศษ"
 * ซึ่งกินโทเคนและทำให้โมเดลไขว้เขว
 */
export function salesStyleContext(style: ScriptStyle, proof: ProofPoint[]): string {
  if (style === 'informative') return ''

  return [
    'โทนการเล่า: ชวนให้ลงมือ (direct response)',
    '',
    'เรียงตามจังหวะนี้:',
    ...SALES_BEATS.map((beat, i) => `${i + 1}. ${beat.label} — ${beat.do} (${beat.why})`),
    '',
    'ข้อห้ามของโทนนี้:',
    ...SALES_RULES.map((rule) => `- ${rule}`),
    '',
    proofContext(proof),
  ].join('\n')
}
