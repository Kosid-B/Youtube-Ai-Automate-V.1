/**
 * ช็อต — ภาพหนึ่งใบครอบหลายฉาก
 *
 * เดิมระบบผูก "ฉาก" (ท่อนเสียง+ซับ) กับ "ภาพ" เป็นหนึ่งต่อหนึ่ง คือภาพเปลี่ยนทุก ~15 วินาที
 * ซึ่งผิดกับวิธีที่ช่องเล่าเรื่องยาวเขาทำกันจริง ๆ — เขาแยกจังหวะเสียงออกจากจังหวะภาพ
 * เสียงกับซับเปลี่ยนทุกไม่กี่วินาที ส่วนภาพค้าง 30–90 วินาที
 *
 * ทำไมต้องแก้ ไม่ใช่แค่เรื่องความสวย:
 *
 * 1. **โควตา Pexels** — 200 คำค้นต่อชั่วโมง · คลิป 45 นาทีแบบภาพต่อฉาก = 180 คำค้น
 *    = กินโควตาเกือบทั้งชั่วโมงเพื่อคลิปเดียว และพลาดนิดเดียว (ต้องถอยไปคำค้นสำรอง)
 *    ก็ทะลุ 200 ทันที · คลิปยาวพิเศษจึงรันไม่ได้จริงถ้าไม่แก้ตรงนี้
 * 2. **เวลาเรนเดอร์** — ทุกภาพคือหนึ่งสาย zoompan บวกหนึ่ง xfade
 *    วัดจริงที่ 1080p คลิป 60 วินาที: 4 ภาพ = 199 วินาที · 1 ภาพ = 128 วินาที
 * 3. **คนดู** — ภาพกระพริบทุก 15 วินาทีตลอด 45 นาทีทำให้เหนื่อยตา
 *    สารคดีจริงค้างภาพนานกว่านั้นมากแล้วใช้ Ken Burns ช้า ๆ แทนการตัด
 */
import { groupByDuration, type Group } from '@/lib/grouping'

export type Shot = Group

/**
 * จัดฉากเข้าช็อตตามความยาวภาพที่ตั้งใจ
 *
 * คลิปสั้น (Shorts) ตั้ง shotSeconds ให้สั้นกว่าหนึ่งฉาก → ได้ช็อตละฉากเหมือนเดิมทุกประการ
 * เพราะคนเลื่อนผ่านเร็ว ภาพต้องเปลี่ยนถี่ ไม่ใช่ค้างนาน
 */
export function planShots(durationsSec: number[], shotSeconds: number): Shot[] {
  return groupByDuration(durationsSec, shotSeconds)
}

/**
 * ข้อความรวมของช็อตหนึ่ง เอาไว้ให้โมเดลคิดคำค้นภาพ
 *
 * ต้องส่งข้อความของ "ทุกฉากในช็อต" ไม่ใช่แค่ฉากแรก — ภาพใบนี้ต้องอยู่ให้ครบทั้งช็อต
 * เลือกจากฉากแรกฉากเดียวจะได้ภาพที่ตรงกับ 15 วินาทีแรกแล้วหลุดบริบทไปอีกนาที
 */
export function shotText(scenes: readonly { text: string }[], shot: Shot): string {
  return scenes
    .slice(shot.start, shot.end)
    .map((scene) => scene.text)
    .join(' ')
}

/** จำนวนฉากที่แต่ละช็อตครอบ — รูปแบบที่ buildRenderPlan รับ */
export function shotSceneCounts(shots: Shot[]): number[] {
  return shots.map((shot) => shot.end - shot.start)
}
