/**
 * แบ่งคลิปยาวเป็นช่วง ๆ เรนเดอร์ทีละช่วง แล้วต่อกันด้วย concat
 *
 * ทำไมต้องแบ่ง — สองเหตุผล ทั้งคู่วัดมาแล้วไม่ใช่เดา:
 *
 * 1. เวลา: วัดจริงที่ 1920x1080 (4 ฉาก มี xfade และซับครบ) เรนเดอร์ใช้เวลา
 *    ราว 1.1 เท่าของความยาวคลิป → คลิป 45 นาทีใช้เวลาราว 50 นาที เกินเพดาน
 *    ffmpeg ของ worker (20 นาที) ไปไกล · แบ่งเป็นช่วงแล้วเพดานนับต่อช่วง ไม่ใช่ทั้งคลิป
 *
 * 2. ขนาดคำสั่ง: คำสั่งเดียวเปิดไฟล์เข้า 2 ไฟล์ต่อฉาก (ภาพ+เสียง) และต่อ filter
 *    zoompan ต่อกันหนึ่งสายต่อฉาก · คลิป 45 นาที ≈ 180 ฉาก = เปิด 360 ไฟล์พร้อมกัน
 *    ในคำสั่งเดียว ซึ่งชนเพดาน file descriptor และกินแรมจน ffmpeg ตายก่อนถึง timeout ด้วยซ้ำ
 *
 * ⚠️ สิ่งที่เสียไปจากการแบ่ง: รอยต่อระหว่างช่วงเป็น "ตัดตรง" ไม่มีเฟดข้าม
 * (ช็อตสุดท้ายของช่วงไม่มีหางให้ช็อตแรกของช่วงถัดไปทับ) — ยอมรับได้เพราะรอยต่อ
 * ห่างกัน 6 นาที และไปตกที่จุดเปลี่ยนภาพพอดีอยู่แล้ว แต่ต้องรู้ว่าเป็นผลจากการแบ่ง
 */

import { groupByDuration, type Group } from '@/lib/grouping'

/**
 * ความยาวที่ตั้งใจต่อหนึ่งช่วง
 *
 * เลือกจากอัตราที่วัดได้จริง 1.1 เท่าที่ 1080p → ช่วงละ 6 นาทีใช้เวลาเรนเดอร์ ~6.6 นาที
 * เหลือที่ว่างถึงเพดาน 20 นาทีอีกราว 3 เท่า เผื่อเครื่องช้ากว่าเครื่องที่วัด
 *
 * ⚠️ ค่านี้ผูกกับอัตราเรนเดอร์โดยตรง ถ้าวันไหนแก้ตัวขยายก่อน zoompan
 * (upscaleFactor ใน lib/ffmpeg.ts) ให้กลับไปแพงขึ้น ต้องลดค่านี้ตามด้วย —
 * ตอนใช้ ×4 อัตราคือ 3.3 เท่า ซึ่งทำให้ช่วง 6 นาทีกินเวลา 19.8 นาที = ชนเพดานพอดี
 */
export const CHUNK_TARGET_SECONDS = 360

/** ดัชนีที่ Chunk อ้างถึงคือ "ช็อต" ไม่ใช่ฉาก — ดู planChunks */
export type Chunk = Group

/**
 * จัดช็อตเข้าช่วงเรนเดอร์ โดยไม่ตัดกลางช็อต
 *
 * ⚠️ รับความยาวของ "ช็อต" ไม่ใช่ของฉาก — จงใจ
 * ถ้าแบ่งช่วงที่ระดับฉาก รอยต่อของช่วงจะไปตกกลางช็อตได้ แปลว่าภาพใบเดียวกัน
 * ถูกตัดเป็นสองไฟล์แล้ว Ken Burns เริ่มใหม่ตรงรอยต่อ — เห็นเป็นภาพกระตุกรีเซ็ต
 * แบ่งที่ระดับช็อตจึงได้รอยต่อที่ตรงกับจุดเปลี่ยนภาพพอดีเสมอ
 *
 * ช็อตที่ยาวเกินเป้าเองก็ยังต้องได้อยู่ในช่วงของตัวเอง — ช่วงจึงยาวเกินเป้าได้
 */
export function planChunks(
  shotSeconds: number[],
  targetSeconds: number = CHUNK_TARGET_SECONDS,
): Chunk[] {
  return groupByDuration(shotSeconds, targetSeconds)
}

/**
 * เนื้อไฟล์รายการสำหรับ concat demuxer ของ ffmpeg
 *
 * รูปแบบคือ `file '<path>'` บรรทัดละไฟล์ · เครื่องหมาย ' ในชื่อไฟล์ต้องปิดวงแล้ว
 * ใส่ '\'' แล้วเปิดวงใหม่ ตามไวยากรณ์ของ demuxer ตัวนี้ (ไม่ใช่ backslash escape ธรรมดา)
 *
 * ใช้ single quote เสมอแม้ชื่อไฟล์ไม่มีช่องว่าง เพราะพาธชั่วคราวมาจาก mkdtemp
 * ซึ่งมีอักขระอะไรก็ได้ตาม TMPDIR ของเครื่องที่รัน
 */
export function concatListFile(paths: string[]): string {
  return paths.map((path) => `file '${path.replace(/'/g, "'\\''")}'`).join('\n') + '\n'
}
